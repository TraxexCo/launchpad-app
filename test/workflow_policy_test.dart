import 'package:flutter_test/flutter_test.dart';
import 'package:launchpad_app/core/app_route_policy.dart';
import 'package:launchpad_app/core/contract_lifecycle.dart';

void main() {
  group('contract lifecycle', () {
    test('paid project follows the full approval and revision path', () {
      expect(ContractLifecycle.canStart('funded'), isTrue);
      expect(ContractLifecycle.canSubmit('in_progress'), isTrue);
      expect(ContractLifecycle.canReview('submitted'), isTrue);
      expect(ContractLifecycle.canSubmit('revision_requested'), isTrue);
      expect(ContractLifecycle.canReview('completed'), isFalse);
    });

    test('funded work cannot bypass moderation through cancellation', () {
      expect(
        ContractLifecycle.canCancel(status: 'in_progress', funded: true),
        isFalse,
      );
      expect(ContractLifecycle.canDispute('in_progress'), isTrue);
      expect(ContractLifecycle.canDispute('completed'), isFalse);
    });

    test('terminal and unknown states expose no invalid actions', () {
      for (final state in ['completed', 'cancelled', 'disputed', 'unknown']) {
        expect(ContractLifecycle.canStart(state), isFalse);
        expect(ContractLifecycle.canSubmit(state), isFalse);
        expect(ContractLifecycle.canReview(state), isFalse);
      }
    });
  });

  group('notification route policy', () {
    test('accepts destinations generated by LaunchPad', () {
      expect(AppRoutePolicy.isSafeNotificationRoute('/contract/42'), isTrue);
      expect(
        AppRoutePolicy.isSafeNotificationRoute('/payment/42?student=1'),
        isTrue,
      );
      expect(
        AppRoutePolicy.isSafeNotificationRoute('/chat/abc?name=Pat'),
        isTrue,
      );
      expect(AppRoutePolicy.isSafeNotificationRoute('/student/jobs'), isTrue);
    });

    test('rejects external, malformed and privileged destinations', () {
      expect(
        AppRoutePolicy.isSafeNotificationRoute('https://example.com'),
        isFalse,
      );
      expect(AppRoutePolicy.isSafeNotificationRoute('/contract/0'), isFalse);
      expect(AppRoutePolicy.isSafeNotificationRoute('/../admin'), isFalse);
      expect(AppRoutePolicy.isSafeNotificationRoute('/admin'), isFalse);
      expect(AppRoutePolicy.isSafeNotificationRoute(null), isFalse);
    });
  });

  group('role route policy', () {
    test('each account type resolves to its own dashboard', () {
      expect(AppRoutePolicy.homeForRole('student'), '/student');
      expect(AppRoutePolicy.homeForRole('business'), '/business');
      expect(AppRoutePolicy.homeForRole('admin'), '/admin');
    });

    test('only marketplace participants can open payment screens', () {
      expect(AppRoutePolicy.canOpenPayment('student'), isTrue);
      expect(AppRoutePolicy.canOpenPayment('business'), isTrue);
      expect(AppRoutePolicy.canOpenPayment('admin'), isFalse);
    });

    test('admin console requires both web and allowlist access', () {
      expect(
        AppRoutePolicy.canUseAdminConsole(isWeb: true, allowlisted: true),
        isTrue,
      );
      expect(
        AppRoutePolicy.canUseAdminConsole(isWeb: false, allowlisted: true),
        isFalse,
      );
      expect(
        AppRoutePolicy.canUseAdminConsole(isWeb: true, allowlisted: false),
        isFalse,
      );
    });
  });
}
